"""
SQLAlchemy ORM models for the Smart Home Activity Recognition System.
Layer 4: Storage Layer - Database Schema
"""

from datetime import datetime
from sqlalchemy import (
    Column, Integer, String, Float, DateTime, Boolean,
    Text, ForeignKey, JSON, Index
)
from sqlalchemy.orm import relationship
from app.core.database import Base


class SensorEvent(Base):
    """Raw sensor events ingested from uploaded datasets or the simulator."""
    __tablename__ = "sensor_events"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, nullable=False, index=True)
    sensor_id = Column(String(64), nullable=False, index=True)
    sensor_type = Column(String(64), nullable=False)
    sensor_state = Column(String(64), nullable=False)
    resident_id = Column(String(64), nullable=True)
    activity_label = Column(String(128), nullable=True)  # ground-truth from datasets
    source = Column(String(32), nullable=False, default="simulator")  # "dataset" | "simulator"
    dataset_name = Column(String(128), nullable=True)
    raw_value = Column(Float, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    __table_args__ = (
        Index("ix_sensor_events_ts_sensor", "timestamp", "sensor_id"),
    )


class ActivityPrediction(Base):
    """Predictions produced by the Intelligence Layer."""
    __tablename__ = "activity_predictions"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, nullable=False, index=True)
    predicted_activity = Column(String(128), nullable=False)
    confidence = Column(Float, nullable=False)
    resident_id = Column(String(64), nullable=True, index=True)
    model_name = Column(String(128), nullable=False, default="demo")
    is_demo = Column(Boolean, default=True)  # True = simulated / demo, False = real model
    window_start = Column(DateTime, nullable=True)
    window_end = Column(DateTime, nullable=True)
    anomaly_score = Column(Float, nullable=True)
    is_anomaly = Column(Boolean, default=False)
    ground_truth = Column(String(128), nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    # Relationships
    explanations = relationship("PredictionExplanation", back_populates="prediction", cascade="all, delete-orphan")
    alerts = relationship("AnomalyAlert", back_populates="prediction", cascade="all, delete-orphan")


class PredictionExplanation(Base):
    """MO-TLIME style explainability outputs for each prediction."""
    __tablename__ = "prediction_explanations"

    id = Column(Integer, primary_key=True, index=True)
    prediction_id = Column(Integer, ForeignKey("activity_predictions.id"), nullable=False)
    sensor_id = Column(String(64), nullable=False)
    feature_name = Column(String(128), nullable=False)
    importance_score = Column(Float, nullable=False)
    direction = Column(String(16), nullable=False, default="positive")  # "positive" | "negative"
    explanation_text = Column(Text, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    prediction = relationship("ActivityPrediction", back_populates="explanations")


class RoutineProfile(Base):
    """Learned daily routine profiles per resident."""
    __tablename__ = "routine_profiles"

    id = Column(Integer, primary_key=True, index=True)
    resident_id = Column(String(64), nullable=False, index=True)
    profile_date = Column(DateTime, nullable=False, index=True)
    activity_sequence = Column(JSON, nullable=False)   # list of {activity, time, duration}
    profile_metadata = Column(JSON, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    __table_args__ = (
        Index("ix_routine_resident_date", "resident_id", "profile_date"),
    )


class AnomalyAlert(Base):
    """Anomaly alerts generated by the Intelligence Layer."""
    __tablename__ = "anomaly_alerts"

    id = Column(Integer, primary_key=True, index=True)
    prediction_id = Column(Integer, ForeignKey("activity_predictions.id"), nullable=True)
    timestamp = Column(DateTime, nullable=False, index=True)
    severity = Column(String(16), nullable=False, default="low")  # low | medium | high | critical
    anomaly_score = Column(Float, nullable=False)
    reason = Column(Text, nullable=False)
    resident_id = Column(String(64), nullable=True)
    affected_sensors = Column(JSON, nullable=True)   # list of sensor_ids
    status = Column(String(16), nullable=False, default="active")  # active | acknowledged | resolved
    created_at = Column(DateTime, default=datetime.utcnow)

    prediction = relationship("ActivityPrediction", back_populates="alerts")


class SensorMetadata(Base):
    """Metadata registry for known sensors in the system."""
    __tablename__ = "sensor_metadata"

    id = Column(Integer, primary_key=True, index=True)
    sensor_id = Column(String(64), unique=True, nullable=False, index=True)
    sensor_type = Column(String(64), nullable=False)
    location = Column(String(128), nullable=True)
    description = Column(Text, nullable=True)
    is_active = Column(Boolean, default=True)
    dataset_source = Column(String(128), nullable=True)  # ARAS | CASAS | custom
    created_at = Column(DateTime, default=datetime.utcnow)


class DatasetUpload(Base):
    """Records of uploaded dataset files."""
    __tablename__ = "dataset_uploads"

    id = Column(Integer, primary_key=True, index=True)
    filename = Column(String(256), nullable=False)
    dataset_type = Column(String(32), nullable=False)  # ARAS | CASAS | custom
    upload_timestamp = Column(DateTime, default=datetime.utcnow)
    record_count = Column(Integer, nullable=True)
    processed_count = Column(Integer, nullable=True)
    status = Column(String(32), nullable=False, default="pending")  # pending | processing | done | error
    error_message = Column(Text, nullable=True)
    stats = Column(JSON, nullable=True)  # preprocessing statistics
    created_at = Column(DateTime, default=datetime.utcnow)
